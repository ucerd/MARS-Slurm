#!/usr/bin/env python3
"""Summarize fresh MARS Reviewer 1 experiments (3 replicates per mode).

Usage: python3 compare_reviewer1_validation.py --root reviewer1_validation
Reads summary.json files generated by run_reviewer1_validation.py. Values are
means and SAMPLE standard deviations of campaign means, NOT pooled job SDs.
Only complete 50-job campaigns with valid accounting participate.
"""
import argparse
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path

METRICS = [
    'eligible_to_end_s', 'submit_to_end_s', 'release_to_end_s',
    'release_to_submit_s', 'submit_to_start_s', 'start_to_end_s',
    'decision_time_s', 'release_delay_s',
    'campaign_makespan_from_first_planned_release_s',
    'mean_gpu_utilization_pct', 'sampled_gpu_energy_kwh'
]
MODES = ('baseline', 'admission_only', 'mars')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', default='reviewer1_validation')
    p.add_argument('--expected-reps', type=int, default=3)
    args = p.parse_args()
    root = Path(args.root)
    seen = defaultdict(list)
    issues = []
    for path in sorted(root.glob('*/summary.json')):
        data = json.loads(path.read_text())
        mode = data.get('mode')
        rep = data.get('rep')
        n = data.get('n_valid_completed')
        total = data.get('n_jobs')
        if mode not in MODES:
            issues.append(f'Unexpected mode in {path}: {mode}')
            continue
        if n != 50 or total != 50:
            issues.append(f'EXCLUDED incomplete campaign: {path} {n}/{total}')
            continue
        if any(x.get('rep') == rep for x, _ in seen[mode]):
            issues.append(f'Duplicate accepted repetition {mode} rep{rep}: {path}')
            continue
        seen[mode].append((data, path))
    out = []
    for mode in MODES:
        campaigns = sorted(seen.get(mode, []), key=lambda d: d[0]['rep'])
        if len(campaigns) != args.expected_reps:
            issues.append(f'{mode}: {len(campaigns)} complete campaigns; expected {args.expected_reps}')
        for metric in METRICS:
            vals = []
            for data, _ in campaigns:
                value = (data.get(metric)
                         if metric in {'campaign_makespan_from_first_planned_release_s',
                                       'mean_gpu_utilization_pct', 'sampled_gpu_energy_kwh'}
                         else data.get('metrics', {}).get(metric, {}).get('mean'))
                if value is not None:
                    vals.append(float(value))
            out.append({
                'mode': mode, 'metric': metric, 'campaign_n': len(vals),
                'mean_campaign_mean': round(statistics.mean(vals), 6) if vals else '',
                'sample_std_of_campaign_means': round(statistics.stdev(vals), 6) if len(vals) >= 2 else ''
            })
    root.mkdir(parents=True, exist_ok=True)
    with (root / 'comparison_reviewer1.csv').open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(out[0]))
        w.writeheader()
        w.writerows(out)
    lines = ['MARS-Slurm | Reviewer 1 new-validation comparison', '='*60,
             'Reported SD is the SAMPLE standard deviation of campaign means.',
             'NO inference of 2026-09 eligibility time from these new data.', '']
    for metric in METRICS:
        lines.append(metric)
        for row in [r for r in out if r['metric'] == metric]:
            lines.append(f"  {row['mode']:<17} n={row['campaign_n']}  "
                         f"mean={row['mean_campaign_mean']}  "
                         f"SD={row['sample_std_of_campaign_means']}")
        lines.append('')
    if issues:
        lines.extend(['ISSUES / SUBMISSION BLOCKERS', '-'*60, *issues])
    else:
        lines.append('All expected campaigns complete; review job-level data and experimental confounds before manuscript use.')
    (root / 'comparison_reviewer1.txt').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    print('\nFiles:', root / 'comparison_reviewer1.csv', root / 'comparison_reviewer1.txt')


if __name__ == '__main__':
    main()
